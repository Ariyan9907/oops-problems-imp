package com.bridglabz.problem4;

public class Utility {
    public static int add(int a,int b){
        return a+b;
    }

    public static int add(int a,int b,int c){
        return a+b+c;
    }

    public static float add(float a,float b){
        return a+b;
    }

    public static float add(int a,float b){
        return a+b;
    }
}
